# ARITHMETIC OPERATORS
print(5+2)
print(5-2)
print(5*2)
print(5/2)
print(5//2) #Integer division output will be a integer
print(5%2) # this will return remainder
print(5**2) #powerof operator this will result as 5^2

# RELATIONAL OPERATOR
print(7>10)
print(4>=4)
print(4<=4)
print(7==7)
print(7!=10)


# Logical Operators
print(7 and 5)
print(1 or 0)
print(not 4)

# Bitwise Operators
# bitwise and
print(5 & 7)
# bitwise or
print(5 | 7)
# bitwise xor
print(2^3)